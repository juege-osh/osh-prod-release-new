create table if not exists release_change_item (
  id bigint generated by default as identity primary key,
  change_id bigint not null,
  item_key varchar(96) not null,
  item_order integer not null,
  component_key varchar(64) not null,
  component_name varchar(128) not null,
  component_type varchar(32) not null,
  owner_username varchar(64) not null,
  owner_display_name varchar(64) not null,
  title varchar(160) not null,
  change_content text not null,
  incremental_plan text not null,
  rollback_plan text not null,
  test_plan text not null,
  data_probe_plan text not null,
  spec_status varchar(32) not null,
  lifecycle_status varchar(32) not null,
  reviewer_a_confirmed boolean not null default false,
  reviewer_b_confirmed boolean not null default false,
  juege_confirmed boolean not null default false,
  created_at timestamp not null,
  updated_at timestamp not null,
  constraint fk_change_item_change foreign key (change_id) references release_change(id) on delete cascade
);

create table if not exists reviewer_test_evidence (
  id bigint generated by default as identity primary key,
  change_id bigint not null,
  item_id bigint,
  component_key varchar(64) not null,
  reviewer_username varchar(64) not null,
  reviewer_display_name varchar(64) not null,
  test_type varchar(32) not null,
  environment_code varchar(64) not null,
  passed boolean not null,
  demo_observed boolean not null default false,
  responsibility_accepted boolean not null default true,
  evidence text not null,
  created_at timestamp not null,
  updated_at timestamp not null,
  constraint fk_reviewer_test_change foreign key (change_id) references release_change(id) on delete cascade,
  constraint fk_reviewer_test_item foreign key (item_id) references release_change_item(id) on delete cascade
);

create table if not exists release_operation_record (
  id bigint generated by default as identity primary key,
  change_id bigint not null,
  operation_type varchar(48) not null,
  operation_status varchar(32) not null,
  environment_code varchar(64) not null,
  target_color varchar(16) not null,
  actor_username varchar(64) not null,
  actor_display_name varchar(64) not null,
  safe_mode boolean not null default true,
  summary varchar(512) not null,
  detail_json text not null,
  created_at timestamp not null,
  updated_at timestamp not null,
  constraint fk_release_operation_change foreign key (change_id) references release_change(id) on delete cascade
);
